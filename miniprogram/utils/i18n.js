// 当前界面语言：'zh' | 'en'。
function lang() {
  let preference = ''
  try {
    preference = wx.getStorageSync(LANG_KEY)
  } catch (e) {
    preference = ''
  }
  if (preference === 'zh' || preference === 'en') return preference
  return /^zh/i.test(wx.getAppBaseInfo().language || '') ? 'zh' : 'en'
}

function t() {
  return STRINGS[lang()]
}

module.exports = { LANG_KEY, STRINGS, lang, t }
