function systemLang() {
  return /^zh/i.test(wx.getAppBaseInfo().language || '') ? 'zh' : 'en'
}

function preference() {
  const value = storage.get(PREF_KEY, 'auto')
  return PREFERENCES.indexOf(value) === -1 ? 'auto' : value
}

function setPreference(value) {
  storage.set(PREF_KEY, PREFERENCES.indexOf(value) === -1 ? 'auto' : value)
}

// 当前界面语言：'zh' | 'en'。
function lang() {
  const value = preference()
  return value === 'auto' ? systemLang() : value
}

function t() {
  return STRINGS[lang()]
}

// 给页面 setData 用的优化方式列表 [{ id, name, desc }]。
function modeOptions(strings) {
  return MODE_IDS.map((id) => ({ id, name: strings.modes[id].name, desc: strings.modes[id].desc }))
}

// api.js 的错误 → 给用户看的一句话。中文界面优先用服务端的中文说明；英文界面按错误码查表。
function errorMessage(error, strings) {
  if (strings === STRINGS.zh && error.message) return error.message
  return strings.errors[error.code] || strings.errors.unknown
}

module.exports = { MODE_IDS, PREFERENCES, STRINGS, preference, setPreference, lang, t, modeOptions, errorMessage }
